function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="pt-BR">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    const { data: sub } = supabase.auth.onAuthStateChange((event) => {
      if (
        event !== "SIGNED_IN" &&
        event !== "SIGNED_OUT" &&
        event !== "USER_UPDATED"
      )
        return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
    });
    return () => sub.subscription.unsubscribe();
  }, [router, queryClient]);

  // Cache offline + ressincronização automática ao voltar a internet.
  useEffect(() => {
    const stop = enableOfflinePersistence(queryClient);
    const resync = () => {
      void queryClient.refetchQueries();
      void router.invalidate();
    };
    window.addEventListener("infinitlog:resync", resync);
    return () => {
      window.removeEventListener("infinitlog:resync", resync);
      stop();
    };
  }, [queryClient, router]);

  return (
    <QueryClientProvider client={queryClient}>
      <PwaProvider>
        <Outlet />
        <Toaster position="top-center" richColors />
      </PwaProvider>
    </QueryClientProvider>
  );
}
